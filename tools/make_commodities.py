"""Regenerate `EDMultitool/edmultitool/catalog/commodities.py` — MANUAL ONLY, two live calls (≤ 1/s).

Commodity names come from Spansh's market field values (the exact spelling its market filter takes); each
name is paired with Ardent's commodity symbol (Ardent's nearby searches take the symbol, not the name). A
name whose symbol is not simply the name squeezed together ("Low Temperature Diamonds" →
"lowtemperaturediamond") is paired by the table below; a name with no symbol at Ardent gets "" (no backup
search for it). Station types: every Spansh type except the fleet carriers'.

Usage (from repo root, after `. tools/env.ps1`):
    .venv/Scripts/python tools/make_commodities.py
"""

import json
import re
import sys
import threading
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "EDMultitool"))

from edmultitool import USER_AGENT
from edmultitool.sources.http import PoliteClient, requests_transport

OUT = Path(__file__).resolve().parents[1] / "EDMultitool" / "edmultitool" / "catalog" / "commodities.py"

# Game symbols that differ from the squeezed name (facts of the game's own commodity list).
SYMBOLS = {
    "Agri-Medicines": "agriculturalmedicines",
    "Atmospheric Processors": "atmosphericextractors",
    "Commercial Samples": "comercialsamples",
    "Encrypted Data Storage": "encripteddatastorage",
    "Energy Grid Assembly": "powergridassembly",
    "H.E. Suits": "hazardousenvironmentsuits",
    "Hardware Diagnostic Sensor": "diagnosticsensor",
    "Land Enrichment Systems": "terrainenrichmentsystems",
    "Large Survey Data Cache": "largeexplorationdatacash",
    "Low Temperature Diamonds": "lowtemperaturediamond",
    "Marine Equipment": "marinesupplies",
    "Micro-weave Cooling Hoses": "coolinghoses",
    "Microbial Furnaces": "heliostaticfurnaces",
    "Muon Imager": "mutomimager",
    "Narcotics": "basicnarcotics",
    "Occupied Escape Pod": "occupiedcryopod",
    "Platinum Alloy": "platinumaloy",
    "Political Prisoners": "politicalprisoner",
    "Hostages": "hostage",
    "Power Transfer Bus": "powertransferconduits",
    "Skimmer Components": "skimercomponents",
    "Small Survey Data Cache": "smallexplorationdatacash",
    "Unoccupied Escape Pod": "damagedescapepod",
    "Void Opal": "opal",
}
CARRIER_TYPES = ("Drake-Class Carrier",)


def squeeze(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", name.lower())


def main() -> int:
    client = PoliteClient(requests_transport(), user_agent=USER_AGENT, cache_dir=None)
    cancel = threading.Event()
    market = client.get("https://spansh.co.uk/api/stations/field_values/market", cancel).json()["min_max"]
    types = client.get("https://spansh.co.uk/api/stations/field_values/type", cancel).json()["min_max"]
    ardent = client.get("https://api.ardent-insight.com/v2/commodities", cancel).json()
    symbols = {r["commodityName"] for r in ardent if " " not in r["commodityName"]}

    pairs: dict[str, str] = {}
    for name in sorted(market, key=str.casefold):
        symbol = SYMBOLS.get(name) or squeeze(name)
        pairs[name] = symbol if symbol in symbols else ""
    bad = [n for n, s in SYMBOLS.items() if n in pairs and not pairs[n]]
    if bad:
        print(f"symbols Ardent does not know: {bad}")
    station_types = sorted(t for t in types if t not in CARRIER_TYPES and "Carrier" not in t)

    lines = [
        '"""Commodity names as Spansh\'s market filter spells them, each with Ardent\'s symbol',
        '("" = Ardent has none: no backup search), and every Spansh station type except fleet carriers.',
        'GENERATED by `tools/make_commodities.py` from both services\' own lists — do not edit by hand."""',
        "",
        "COMMODITIES: dict[str, str] = {",
        *(f"    {json.dumps(n, ensure_ascii=False)}: {json.dumps(s)}," for n, s in pairs.items()),
        "}",
        "",
        "STATION_TYPES: tuple[str, ...] = (",
        *(f"    {json.dumps(t, ensure_ascii=False)}," for t in station_types),
        ")",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    paired = sum(1 for s in pairs.values() if s)
    print(f"{len(pairs)} commodities ({paired} with an Ardent symbol), {len(station_types)} station types")
    print(f"written to {OUT}")
    print("station types:", station_types)
    return 0


if __name__ == "__main__":
    sys.exit(main())
